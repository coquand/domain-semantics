#!/usr/bin/env python3
"""Emit Seg models for closed universe bounds.

For example, regenerate the checked instances with
    python3 UNIT/gen_ehrhard_v_tower.py 0 1 2 > UNIT/EhrhardVInstances.seg

A bound of N uses Seg levels from k through its Nth successor, and one
further level for the CwF. The generated code dispatches on the
object-language indices. The stage, link, and model proofs are shared.
"""

import argparse


def successors(term, count):
    for _ in range(count):
        term = f"(suc {term})"
    return term


def stage_at(offset):
    return f"stage-from{offset}"


def link_to(lower, offset):
    return f"link-{lower}-to-from{offset}"


def link_at(offset):
    return f"link-from{offset}"


def render_model(bound):
    top = "k" + "+" * (bound + 1)
    model_level = top + "+"
    lines = [
        f"module Bound{bound} {{",
        f"  open Prelude[{model_level}] ; open Lib[{model_level}] ;",
        f"  module H = EhrhardVHierarchy[{top}] ;",
        f"  module TE = EhrhardTEModel[{model_level}] ;",
        f"  N : Nat = {successors('zero', bound)} ;",
        "",
        "  -- At offset i, the remaining index is at most N - i.",
    ]
    for offset in range(bound, -1, -1):
        remaining = successors("zero", bound - offset)
        level = "k" + "+" * offset
        successor = "\\ h -> efq h" if offset == bound else f"{stage_at(offset + 1)} n"
        lines.extend([
            f"  {stage_at(offset)} : (n : Nat) -> LeN n {remaining} -> H.VStage = split {{",
            f"    zero -> \\ h -> H.StageAt[{level}].stage ; suc n -> {successor} }} ;",
        ])

    lines.extend(["", "  -- Fix the source stage, then dispatch on the target."])
    for lower in range(bound + 1):
        low_level = "k" + "+" * lower
        for offset in range(bound, -1, -1):
            remaining = successors("zero", bound - offset)
            high_level = "k" + "+" * offset
            strict = f"LeN {successors('zero', lower + 1)} {successors('n', offset)}"
            target = (
                f"H.LinkAt[{low_level},{high_level}].link"
                if lower < offset
                else "efq lt"
            )
            successor = (
                "\\ nb lt -> efq nb"
                if offset == bound
                else f"{link_to(lower, offset + 1)} n"
            )
            lines.extend([
                f"  {link_to(lower, offset)} : (n : Nat) -> (nb : LeN n {remaining}) -> {strict}",
                f"      -> H.VLink[H.StageAt[{low_level}].stage,{stage_at(offset)} n nb] = split {{",
                f"    zero -> \\ nb lt -> {target} ; suc n -> {successor} }} ;",
            ])

    lines.extend(["", "  -- Dispatch on the source to select the corresponding row."])
    for offset in range(bound, -1, -1):
        remaining = successors("zero", bound - offset)
        strict = successors("m", offset + 1)
        successor = "\\ mb -> efq mb" if offset == bound else f"{link_at(offset + 1)} m"
        lines.extend([
            f"  {link_at(offset)} : (m : Nat) -> (mb : LeN m {remaining}) -> (n : Nat) -> (nb : LeN n N) -> LeN {strict} n",
            f"      -> H.VLink[{stage_at(offset)} m mb,{stage_at(0)} n nb] = split {{",
            f"    zero -> \\ mb -> {link_to(offset, 0)} ; suc m -> {successor} }} ;",
        ])

    lines.extend([
        "",
        "  hierarchy : H.VHierarchy[N] = new H.VHierarchy[N,",
        f"    stage := \\ n -> {stage_at(0)} n.1 n.2,",
        f"    link := \\ m n lt -> {link_at(0)} m.1 m.2 n.1 n.2 lt] ;",
        f"  model : TE.TEModel[N] = EhrhardVModel[{top}].vModel N hierarchy ;",
        "} ;",
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("bounds", nargs="+", type=int, help="nonnegative universe bounds")
    args = parser.parse_args()
    if min(args.bounds) < 0 or len(set(args.bounds)) != len(args.bounds):
        parser.error("supply distinct nonnegative bounds")
    print("-- Generated by gen_ehrhard_v_tower.py.")
    print("level k ;")
    print("open Base ;")
    for bound in args.bounds:
        print()
        print(render_model(bound))


if __name__ == "__main__":
    main()
