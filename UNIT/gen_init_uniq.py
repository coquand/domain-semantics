#!/usr/bin/env python3
"""Emit the uniqueness induction of PLAN-INIT Part U from the GDer declaration.

Regenerate with python3 UNIT/gen_init_uniq.py > UNIT/InitUniqInd.seg.
A constructor whose conclusion is an equality judgement (gjeq*) gives tt
(QJ is Top there); every other constructor delegates to case-<name>
(InitUniqCaseA/B), passing ALL its binders (raw data, derivations, level
bounds) and then the induction hypotheses in premise order.
"""

from pathlib import Path
import re


def cases(source):
    declaration = source.split("data GDer :", 1)[1].split(" ;", 1)[0]
    body = declaration.split("=", 1)[1]
    body = re.sub(r"--[^\n]*", "", body).strip()
    for rule in re.split(r"\n\s*\|\s*", body):
        name, rest = rule.split(None, 1)
        pattern = [name]
        binders = []
        hypotheses = []
        while rest.startswith("("):
            depth = 0
            for end, char in enumerate(rest):
                if char == "(":
                    depth += 1
                elif char == ")":
                    depth -= 1
                    if depth == 0:
                        break
            else:
                raise ValueError(f"unclosed binder in {name}")
            names, annotation = rest[1:end].split(":", 1)
            for binder in names.split():
                pattern.append(binder)
                binders.append(binder)
                if annotation.strip().startswith("GDer "):
                    hypotheses.append(f"ih{len(hypotheses) + 1}")
            rest = rest[end + 1:].lstrip()
        if not rest.startswith(":"):
            raise ValueError(f"missing target for {name}")
        target = rest[1:].strip()
        m = re.match(r"GDer\s*\(\s*(gj[a-z]+)", target)
        if not m:
            raise ValueError(f"unexpected target for {name}: {target}")
        if hypotheses:
            pattern.extend(["|", *hypotheses])
        if m.group(1).startswith("gjeq"):
            rhs = "tt"
        else:
            rhs = " ".join([f"case-{name}", *binders, *hypotheses])
        yield " ".join([*pattern, "->", rhs])


HEADER = """\
-- Generated by gen_init_uniq.py from the GDer declaration (PLAN-INIT, Part U).
-- uniq: for two morphisms H, H' : Hom (mk e) M', every derivable judgement
-- satisfies QJ (InitUniqBase): agreement at the canonical class of its
-- subject; equality judgements: tt.
level l ;
open Base ; open Prelude[l] ;
module B = BoundedSyntax[N] ;
open B.GAT[l] ;
module EM = EhrhardTEModel[l] ;
open InitModelShape[l] ;

module Uq (e : Eqs) (M' : EM.TEModel[N]) {
  module Mo = InitHom.Morphism[l, N, mk e, M'] ;
  module HL = Mo.InitHomLaws ;

  module V (H H' : HL.Hom) {
    module Bs = InitUniqBase[l].Uq[e, M'].V[H, H'] ;
    open Bs ;
    module CA = InitUniqCaseA[l].Uq[e, M'].V[H, H'] ;
    open CA ;
    module CB = InitUniqCaseB[l].Uq[e, M'].V[H, H'] ;
    open CB ;
"""


def main():
    gat = Path(__file__).with_name("GAT.seg").read_text()
    print(HEADER)
    print("    uniq : (J : GJ) -> GDer J -> QJ J = split {")
    print("      " + " ;\n      ".join(cases(gat)) + " } ;")
    print("  } ;")
    print("} ;")


if __name__ == "__main__":
    main()
