#!/usr/bin/env python3
"""Emit the syntax-directed soundness induction from the GDer declaration.

Regenerate with python3 UNIT/gen_te_interp.py > UNIT/TEInterpSound.seg.
Each constructor delegates to its semantic case, passing the ordinary
arguments and then the induction hypotheses in premise order.
"""

from pathlib import Path
import re


def cases(source):
    declaration = source.split("data GDer :", 1)[1].split(" ;", 1)[0]
    body = declaration.split("=", 1)[1]
    body = re.sub(r"--[^\n]*", "", body).strip()
    for rule in re.split(r"\n\s*\|\s*", body):
        name, rest = rule.split(None, 1)
        pattern = [name]
        arguments = []
        hypotheses = []
        while rest.startswith("("):
            depth = 0
            for end, char in enumerate(rest):
                if char == "(":
                    depth += 1
                elif char == ")":
                    depth -= 1
                    if depth == 0:
                        break
            else:
                raise ValueError(f"unclosed binder in {name}")
            names, annotation = rest[1:end].split(":", 1)
            for binder in names.split():
                pattern.append(binder)
                if annotation.strip().startswith("GDer "):
                    hypotheses.append(f"ih{len(hypotheses) + 1}")
                else:
                    arguments.append(binder)
            rest = rest[end + 1:].lstrip()
        if not rest.startswith(":"):
            raise ValueError(f"missing target for {name}")
        if hypotheses:
            pattern.extend(["|", *hypotheses])
        yield " ".join([*pattern, "->", f"case-{name}", *arguments, *hypotheses])


def main():
    gat = Path(__file__).with_name("GAT.seg").read_text()
    print("-- Generated by gen_te_interp.py from the GDer declaration.")
    print("open TEDenote ; open B.GAT[l] ; open TEInterpJudgement ;")
    print("open TEInterpStructural ; open TEInterpSubst ; open TEInterpCategory ; open TEInterpComprehension ;")
    print("open TEInterpProducts ; open TEInterpProductNat ;")
    print("open TEInterpUniverses ; open TEInterpUniverseNat ; open TEInterpLifts ;")
    print()
    print("sound : (J : GJ) -> GDer J -> SoundJ J = split {")
    print("  " + " ;\n  ".join(cases(gat)) + " } ;")


if __name__ == "__main__":
    main()
