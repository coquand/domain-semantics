"""Raw-image witnesses for fully annotated constructors."""

from gen_annot import fields
from gen_full_annot import raw_constructors, apply


def expr_rule(full, signature, old, keep):
    params = fields(signature)
    binders, native, raw, erased, ids, holes = [], [], [], [], [], []
    for i, (x, kind) in enumerate(params):
        if i in keep and kind == "FA":
            binders += [f"({x} : GA)", f"(x-{x} : LiftExpr[{x}])"]
            native.append(f"x-{x}.t")
            raw.append(x)
            erased.append(f"(ff x-{x}.t)")
            ids.append(f"x-{x}.image")
            holes.append(f"y-{x}")
        else:
            binders.append(f"({x} : {kind})")
            native.append(x)
            if i in keep:
                raw.append(x)
    image = apply(old, *raw)
    q = iter(holes)
    body = apply(old, *(x if params[i][1] == "Nat" else next(q) for i, x in zip(keep, raw)))
    if not holes:
        path = "refl " + ("(" + image + ")" if raw else image)
    else:
        arity = len(holes)
        head = ("Prelude[l].ap GA GA" if arity == 1 else
                "TSyntax[l].cong2 GA GA GA" if arity == 2 else f"TSyntax[l].cong{arity} GA")
        children = [x for i, (x, k) in enumerate(params) if i in keep and k == "FA"]
        path = apply(head, "(\\ " + " ".join(holes) + " -> " + body + ")",
                     *(p for pair in zip(erased, children) for p in pair), *ids)
    return (
        apply("e-" + full[1:], *binders, f": LiftExpr[{image}] =")
        + f"\n  new LiftExpr[{image}, t := {apply(full, *native)},\n    image := {path}] ;"
    )


def render_expr():
    header = """-- Generated by gen_aannot.py --full. Constructor witnesses of exact raw erasure.
level l ;
open Base ; open AGAT[l] ; open FGAT[l] ; open FForget[l] ;

record LiftExpr { raw : GA ; t : FA ; image : Id GA (ff t) raw } ;"""
    return "\n\n".join((header, *(expr_rule(*entry) for entry in raw_constructors()))) + "\n"
