"""Generate the raw views and structural induction for full annotation coherence."""

from gen_annot import fields, split
from gen_full_annot import RAW, raw_constructors, apply, product


def projection(name, position, size):
    tail = ".2" * position
    return name + tail + (".1" if position + 1 < size else "")


def tuple_text(items):
    return product(items, lambda x, y: f"({x},{y})") if items else "tt"


def cases(signature, rows):
    return split(signature, ["  " + row for row in rows]).rstrip()


class Shape:
    def __init__(self, name, declaration, variants):
        self.name = name
        self.old = fields(declaration)
        self.variants = variants
        if name == "asb":
            self.raw = [("kind", "Bool")] + [(x, "FA") for x in ("D", "G", "A", "t", "s")]
            self.keep = (4, 5)
            self.full_name = "action-expr"
        else:
            self.full_name, sig, _, self.keep = variants[0]
            self.raw = fields(sig)
        self.native = [(i, x, k) for i, (x, k) in enumerate(self.raw) if k != "Nat"]
        self.child_indices = [i for i, (_, k) in enumerate(self.old) if k == "GA"]
        self.size = len(self.native) + len(self.child_indices)

    def pattern(self):
        return apply(self.name, *(x for x, _ in self.old))

    def constructor(self, name):
        """The reconstructed expression, with children viewed through the given record."""
        position = 0
        values = []
        for index, (_, kind) in enumerate(self.raw):
            if kind == "Nat":
                values.append(self.old[self.keep.index(index)][0])
            else:
                values.append(projection(name, position, self.size))
                position += 1
        return values

    def shape(self):
        eqs = [f"Id GA (ff full-{self.raw[self.keep[i]][0]}) {self.old[i][0]}" for i in self.child_indices]
        body = " * ".join(eqs) if eqs else self.native[-1][2] if self.native else "Top"
        binders = self.native if eqs else self.native[:-1]
        return "".join(f"(full-{x} : {kind}) * " for _, x, kind in binders) + body

    def self_cases(self, identity=False):
        for name, sig, _, keep in self.variants:
            params = fields(sig)
            lhs = apply(name, *(x for x, _ in params))
            if identity:
                yield lhs + " -> refl " + ("(" + lhs + ")" if params else lhs)
                continue
            values = [x for x, kind in params if kind == "FA"]
            if name == "ftsb":
                values = ["false", *values[:2], "fnil", *values[2:]]
            elif name == "fmsb":
                values = ["true", *values]
            identities = [f"refl (ff {params[keep[i]][0]})" for i in self.child_indices]
            yield lhs + " -> " + tuple_text([*values, *identities])

    def recursive(self, i, sort):
        position = len(self.native) + self.child_indices.index(i)
        j = self.keep[i]
        operands = [self.constructor(k)[j] for k in ("p", "q")]
        eqs = [projection(k, position, self.size) for k in ("p", "q")]
        slot = {"ty": ".1", "tm": ".2.1", "sub": ".2.2.1", "cx": ".2.2.2"}[sort]
        return "(" + apply("r" + self.old[i][0], *operands, *eqs) + ")" + slot


def shapes():
    variants = list(raw_constructors())
    return [Shape(name, sig, [variant for variant in variants if variant[2] == name]) for name, sig in RAW]


def render_shapes():
    entries = shapes()
    parts = [
        "-- Generated by gen_aannot.py --full. Views at a given raw AGAT image.",
        "level l ;\nopen Base ; open Lib[l] ; open AGAT[l] ; open FGAT[l] ; open FForget[l] ;",
        r"""action-expr : Bool -> FA -> FA -> FA -> FA -> FA -> FA = split {
  false -> \ D G A t s -> ftsb D G t s ;
  true -> \ D G A t s -> fmsb D G A t s } ;""",
        cases("Shape : GA -> U l", [s.pattern() + " -> " + s.shape() for s in entries]),
        cases("shape-term : (a : GA) -> Shape a -> FA", [
            s.pattern() + " -> \\ x -> " + apply(s.full_name, *s.constructor("x")) for s in entries
        ]),
        cases("shape-self : (X : FA) -> Shape (ff X)", [row for s in entries for row in s.self_cases()]),
        cases("shape-self-id : (X : FA) -> Id FA (shape-term (ff X) (shape-self X)) X",
              [row for s in entries for row in s.self_cases(identity=True)]),
        r"""Repr (a : GA) (X : FA) : U l = (s : Shape a) * Id FA (shape-term a s) X ;

shape-view (a : GA) (X : FA) (p : Id GA (ff X) a) : Repr a X =
  Prelude[l].subst GA (\ Y -> Repr Y X) (ff X) a p (shape-self X,shape-self-id X) ;""",
    ]
    return "\n\n".join(parts) + "\n"


# Native comparison cases take child comparisons in the order of the relevant payload.
PLANS = {
    "anil": ("cx", None, ""),
    "aext": ("cx", "extension-compare", "cx ty"),
    "api": ("ty", "pi-frame-compare", "ty ty"),
    "auu": ("ty", "uu-frame-compare", ""),
    "ael": ("ty", "el-frame-compare", "tm"),
    "alam": ("tm", "lam-frame-compare", "ty ty tm"),
    "aapp": ("tm", "app-frame-compare", "ty ty tm tm"),
    "apic": ("tm", "pic-frame-compare", "tm tm"),
    "auc": ("tm", "uc-frame-compare", ""),
    "alf": ("tm", "lf-frame-compare", "tm"),
    "aq": ("tm", "q-frame-compare", ""),
    "aid": ("sub", "id-frame-compare", ""),
    "acomp": ("sub", "comp-frame-compare", "sub sub"),
    "aeps": ("sub", "eps-frame-compare", ""),
    "ap": ("sub", "p-frame-compare", ""),
    "alift": ("sub", "lift-frame-compare", "ty sub"),
    "asec": ("sub", "sec-frame-compare", "ty tm"),
}

SORTS = ("ty", "tm", "sub", "cx")


def absent(sort, left, right):
    return apply("no-" + sort, left, right, "(\\ p -> p)")


def nonaction_case(shape):
    plan_sort, native, roles = PLANS[shape.name]
    left_args, right_args = [shape.constructor(k) for k in ("p", "q")]
    left, right = ["(" + apply(shape.full_name, *xs) + ")" if xs else shape.full_name for xs in (left_args, right_args)]
    levels = [x for x, k in shape.old if k == "Nat"]
    payloads = [[x for x, (_, k) in zip(xs, shape.raw) if k != "Nat"] for xs in (left_args, right_args)]
    rec = [shape.recursive(i, sort) for i, sort in zip(shape.child_indices, roles.split())]
    body = apply(native, *levels, *payloads[0], *payloads[1], *rec) if native else "\\ p q -> fc-nil"
    if plan_sort != "cx":
        body = apply(plan_sort + "-frames", left, right, "(" + body + ")")
    return tuple_text([body if sort == plan_sort else absent(sort, left, right) for sort in SORTS])


def action_case(shape):
    args = [*shape.constructor("p")[:1], *shape.constructor("q")[:1],
            *shape.constructor("p")[1:], *shape.constructor("q")[1:]]
    args += [shape.recursive(0, "ty"), shape.recursive(0, "tm"), shape.recursive(1, "sub")]
    return apply("actions", *args)


def action_dispatch():
    rows = []
    for left in ("false", "true"):
        inner = []
        for right in ("false", "true"):
            xs = "(ftsb D G t s)" if left == "false" else "(fmsb D G A t s)"
            ys = "(ftsb E H u v)" if right == "false" else "(fmsb E H B u v)"
            parts = [absent(sort, xs, ys) for sort in SORTS]
            if left == right == "false":
                parts[0] = f"ty-frames {xs} {ys} (ty-action-frame D G t s E H u v ct cs)"
            elif left == right == "true":
                parts[1] = f"tm-frames {xs} {ys} (term-action-frame D G A t s E H B u v cm cs)"
            elif left == "false":
                parts[0] = f"no-ty-right {xs} {ys} (\\ p -> p)"
            else:
                parts[1] = f"no-tm-right {xs} {ys} (\\ p -> p)"
            inner.append(right + " -> \\ D G A t s E H B u v ct cm cs -> " + tuple_text(parts))
        rows.append(left + " -> split {\n    " + " ;\n    ".join(inner) + " }")
    return cases("""actions : (k j : Bool) -> (D G A t s E H B u v : FA) ->
    TyCompare t u -> TmCompare t u -> SubCompare s v ->
    Compare (action-expr k D G A t s) (action-expr j E H B u v)""", rows)


def render_coherence():
    entries = shapes()
    header = r"""-- Generated by gen_aannot.py --full. Coherence by induction on the common AGAT image.
level l ;
open Base ; open Lib[l] ; open AGAT[l] ; open FGAT[l] ; open FForget[l] ;
open FTyping[l] ; open FCtx[l] ; open FGen[l] ; open FShape[l] ; open FCompareBase[l] ;
open FSubCompare[l] ; open FActionCompare[l] ; open FBinderCompare[l] ; open FUniverseCompare[l] ;

CompareAt (a : GA) : U l = (X Y : FA) -> Id GA (ff X) a -> Id GA (ff Y) a -> Compare X Y ;

compare-shapes (a : GA) (k : (p q : Shape a) -> Compare (shape-term a p) (shape-term a q)) : CompareAt a =
  \ X Y x y -> compare X Y (shape-view a X x) (shape-view a Y y)
 where {
  compare (X Y : FA) (p : Repr a X) (q : Repr a Y) : Compare X Y =
    Prelude[l].subst FA (\ Z -> Compare X Z) (shape-term a q.1) Y q.2
      (Prelude[l].subst FA (\ Z -> Compare Z (shape-term a q.1)) (shape-term a p.1) X p.2 (k p.1 q.1)) ;
 } ;

no-ty (X Y : FA) (k : TyIntro X -> Empty) : TyCompare X Y =
  \ D E e p q -> efq (k (gen-ty D X p).1) ;
no-tm (X Y : FA) (k : TmIntro X -> Empty) : TmCompare X Y =
  \ D E A B e p q -> efq (k (gen-tm D X A p).1) ;
no-sub (X Y : FA) (k : SubIntro X -> Empty) : SubCompare X Y =
  \ D E G H e p q -> efq (k (gen-sub D X G p).1) ;
no-cx (X Y : FA) (k : WfHead X -> Empty) : CxCompare X Y =
  \ p q -> efq (k (ctx-gen (fjwf X) p)) ;
no-ty-right (X Y : FA) (k : TyIntro Y -> Empty) : TyCompare X Y =
  \ D E e p q -> efq (k (gen-ty E Y q).1) ;
no-tm-right (X Y : FA) (k : TmIntro Y -> Empty) : TmCompare X Y =
  \ D E A B e p q -> efq (k (gen-tm E Y B q).1) ;"""
    branches = []
    for s in entries:
        name = s.pattern()
        rec = ["r" + s.old[i][0] for i in s.child_indices]
        body = action_case(s) if s.name == "asb" else nonaction_case(s)
        branches.append(name + (" | " + " ".join(rec) if rec else "")
                        + " -> compare-shapes " + ("(" + name + ")" if s.old else name) + " (\\ p q ->\n    " + body + ")")
    api = """compare-ff (X Y : FA) (e : Id GA (ff X) (ff Y)) : Compare X Y =
  compare-raw (ff Y) X Y e (refl (ff Y)) ;

same-ty (A B : FA) (e : Id GA (ff A) (ff B)) : TyCompare A B = (compare-ff A B e).1 ;
same-tm (a b : FA) (e : Id GA (ff a) (ff b)) : TmCompare a b = (compare-ff a b e).2.1 ;
same-sub (s t : FA) (e : Id GA (ff s) (ff t)) : SubCompare s t = (compare-ff s t e).2.2.1 ;
same-cx (G H : FA) (e : Id GA (ff G) (ff H)) : CxCompare G H = (compare-ff G H e).2.2.2 ;"""
    return "\n\n".join((header, action_dispatch(), cases("compare-raw : (a : GA) -> CompareAt a", branches), api)) + "\n"
